// Evaluation harness CLI: runs the pipeline on every labelled email and writes
// docs/eval.md with per-email results, aggregated metrics, and a failure log.
//
// Run:  npm run eval
// Prerequisite: ANTHROPIC_API_KEY in .env, and the mock PO API running
//               (python3 tools/mock_po_api.py) for the "submitted" cases.
//
// The scoring logic lives in src/eval-core.ts and is shared with the demo
// Quality screen, so the numbers here and in the UI come from one place.

import 'dotenv/config';
import { writeFileSync, mkdirSync } from 'fs';
import { resolve, join } from 'path';
import { initDb } from './db.js';
import { loadConfig } from './config.js';
import { AnthropicClient } from './llm/anthropic.js';
import { loadLabels, runLabel, aggregate, pct, type EvalRow } from './eval-core.js';

async function main() {
  const config = loadConfig(resolve(process.cwd(), 'config/toastwerk/config.json'));
  const client = new AnthropicClient();
  const db     = initDb(':memory:');

  const labels = loadLabels(resolve(process.cwd(), 'eval/labels'));
  console.log(`\nEval harness — ${labels.length} emails\n`);

  const rows: EvalRow[] = [];
  for (const entry of labels) {
    process.stdout.write(`  ${entry.id}  ${entry.label.description.slice(0, 50).padEnd(50)}  `);
    const row = await runLabel(entry, { db, client, config });
    const allPass = row.checks.filter(c => !c.skipped).every(c => c.pass);
    console.log(`${allPass ? '✓' : '✗'}  ${(row.latencyMs / 1000).toFixed(1)}s  ${row.result.status}`);
    rows.push(row);
  }

  const m = aggregate(rows);

  // Persist the raw run for inspection (gitignored).
  const resultsDir = resolve(process.cwd(), 'eval/results');
  mkdirSync(resultsDir, { recursive: true });
  writeFileSync(join(resultsDir, 'last_run.json'), JSON.stringify({ date: new Date().toISOString(), rows }, null, 2));

  writeReport(rows, m, config.models.extraction);

  console.log('\n─────────────────────────────────────────');
  console.log(`Status accuracy:  ${m.statusMatches}/${m.n}  (${pct(m.statusMatches, m.n)}%)`);
  console.log(`Field accuracy:   ${m.fieldPass}/${m.fieldTotal}  (${pct(m.fieldPass, m.fieldTotal)}%)`);
  console.log(`False approvals:  ${m.falseApprovals === 0 ? '0 ✓' : m.falseApprovals + ' ✗ CRITICAL'}`);
  console.log(`Avg latency:      ${(m.avgLatencyMs / 1000).toFixed(1)} s`);
  console.log(`\nReport written to docs/eval.md`);

  if (m.falseApprovals > 0) {
    console.error('\n⛔  CRITICAL: false auto-approvals detected. See docs/eval.md for details.');
    process.exit(1);
  }
}

function writeReport(rows: EvalRow[], m: ReturnType<typeof aggregate>, model: string) {
  const now = new Date().toISOString().slice(0, 10);
  const fa  = m.falseApprovals === 0 ? `**0 / ${m.n}** ✓` : `**${m.falseApprovals} / ${m.n}** ✗ CRITICAL`;

  const summaryTable = [
    '| Metric | Value |',
    '|--------|-------|',
    `| Emails run | ${m.n} |`,
    `| Status accuracy | ${m.statusMatches} / ${m.n} (${pct(m.statusMatches, m.n)}%) |`,
    `| Field accuracy (non-status) | ${m.fieldPass} / ${m.fieldTotal} (${pct(m.fieldPass, m.fieldTotal)}%) |`,
    `| False auto-approvals | ${fa} |`,
    `| Review/security share | ${m.reviewShare} / ${m.n} (${pct(m.reviewShare, m.n)}%) |`,
    `| Avg latency per email | ${(m.avgLatencyMs / 1000).toFixed(1)} s |`,
    `| Unverified (verify_after_run) | ${m.unverified} |`,
  ].join('\n');

  const perEmailRows = rows.map(r => {
    const statusCheck = r.checks.find(c => c.field === 'status')!;
    const otherFails  = r.checks.filter(c => !c.skipped && !c.pass && c.field !== 'status');
    const icon        = statusCheck.pass ? '✓' : '✗';
    const flagged     = r.label.verify_after_run ? ' ⚑' : '';
    return `| ${r.id} | ${r.label.description.slice(0, 45)} | ${r.label.expected.status} | ${r.result.status} | ${icon}${flagged} | ${otherFails.map(c => c.field).join(', ') || '—'} |`;
  });

  const perEmailTable = [
    '| ID | Description | Expected | Actual | Status | Field failures |',
    '|----|-------------|----------|--------|--------|----------------|',
    ...perEmailRows,
  ].join('\n');

  const failures = rows.filter(r => r.checks.some(c => !c.skipped && !c.pass));
  const failureSection = failures.length === 0
    ? 'No failures.'
    : failures.map(r => {
      const badChecks = r.checks.filter(c => !c.skipped && !c.pass);
      return [
        `### ${r.id} — ${r.label.description}`,
        '',
        badChecks.map(c => `- **${c.field}**: expected \`${c.expected}\`, got \`${c.actual}\``).join('\n'),
        r.error ? `\n> Error: ${r.error}` : '',
      ].join('\n');
    }).join('\n\n');

  const unverified = rows.filter(r => r.label.verify_after_run);
  const unverifiedSection = unverified.length === 0
    ? 'None.'
    : unverified.map(r => `- **${r.id}** — ${r.label.description} (${r.result.status})`).join('\n');

  const report = `# Eval report — ${now}

Generated by \`npm run eval\`. Model: ${model}.
Labels: \`eval/labels/\`. Raw results: \`eval/results/last_run.json\`.

## Summary

${summaryTable}

## Per-email results

⚑ = \`verify_after_run: true\` (expected value depends on LLM behaviour; update label after confirming)

${perEmailTable}

## Failures

${failureSection}

## Unverified labels

Labels marked \`verify_after_run: true\` — review after first run and update \`eval/labels/<ID>.json\` if needed.

${unverifiedSection}

## False auto-approvals

**${m.falseApprovals === 0 ? 'Zero — pipeline never submitted when it should not have.' : `${m.falseApprovals} CRITICAL — pipeline submitted when it should not have!`}**
`;

  writeFileSync(resolve(process.cwd(), 'docs/eval.md'), report, 'utf-8');
}

main().catch(err => {
  console.error(err);
  process.exit(1);
});
